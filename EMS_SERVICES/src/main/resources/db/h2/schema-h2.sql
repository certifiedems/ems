-- ems_backend/src/main/resources/db/h2/schema-h2.sql

CREATE TABLE IF NOT EXISTS roles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50)  NOT NULL UNIQUE,
    description VARCHAR(255),
    created_by VARCHAR(100) NOT NULL,
    created_date TIMESTAMP  NOT NULL,
    updated_by VARCHAR(100),
    updated_date TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              VARCHAR(50)  NOT NULL UNIQUE,
    first_name           VARCHAR(100) NOT NULL,
    last_name            VARCHAR(100) NOT NULL,
    email                VARCHAR(255) NOT NULL UNIQUE,
    mobile_number        VARCHAR(20)  NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    profile_photo_key    VARCHAR(255),
    address              VARCHAR(1000),
    years_of_experience  INT,
    current_skill_level  VARCHAR(10)  NOT NULL,
    current_organization VARCHAR(255),
    qualification        VARCHAR(255),
    father_name          VARCHAR(255),
    enabled              BOOLEAN      NOT NULL,
    account_non_locked   BOOLEAN      NOT NULL,
    created_by           VARCHAR(100) NOT NULL,
    created_date         TIMESTAMP    NOT NULL,
    updated_by           VARCHAR(100),
    updated_date         TIMESTAMP,
    CONSTRAINT chk_users_skill_level CHECK (current_skill_level IN ('L1', 'L2', 'L3'))
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id      BIGINT NOT NULL,
    role_id      BIGINT NOT NULL,
    created_by   VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    created_date TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by   VARCHAR(100),
    updated_date TIMESTAMP,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_ref     BIGINT       NOT NULL,
    token_hash   VARCHAR(255) NOT NULL UNIQUE,
    issued_at    TIMESTAMP    NOT NULL,
    expires_at   TIMESTAMP    NOT NULL,
    revoked      BOOLEAN      NOT NULL,
    created_by   VARCHAR(100) NOT NULL,
    created_date TIMESTAMP    NOT NULL,
    updated_by   VARCHAR(100),
    updated_date TIMESTAMP,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_ref) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_ref     BIGINT       NOT NULL,
    token_hash   VARCHAR(255) NOT NULL UNIQUE,
    expires_at   TIMESTAMP    NOT NULL,
    used         BOOLEAN      NOT NULL,
    created_by   VARCHAR(100) NOT NULL,
    created_date TIMESTAMP    NOT NULL,
    updated_by   VARCHAR(100),
    updated_date TIMESTAMP,
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_ref) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS certifications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_ref             BIGINT      NOT NULL,
    certification_level  VARCHAR(10) NOT NULL,
    certification_status VARCHAR(20) NOT NULL,
    issue_date           DATE        NOT NULL,
    expiry_date          DATE        NOT NULL,
    created_by           VARCHAR(100) NOT NULL,
    created_date         TIMESTAMP    NOT NULL,
    updated_by           VARCHAR(100),
    updated_date         TIMESTAMP,
    CONSTRAINT fk_certifications_user FOREIGN KEY (user_ref) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_certification_level  CHECK (certification_level IN ('L1', 'L2', 'L3')),
    CONSTRAINT chk_certification_status CHECK (certification_status IN ('ACTIVE', 'EXPIRED', 'REVOKED'))
);

CREATE TABLE IF NOT EXISTS certification_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certification_ref BIGINT       NOT NULL,
    event_type        VARCHAR(50)  NOT NULL,
    event_description VARCHAR(2000),
    event_timestamp   TIMESTAMP    NOT NULL,
    created_by        VARCHAR(100) NOT NULL,
    created_date      TIMESTAMP    NOT NULL,
    updated_by        VARCHAR(100),
    updated_date      TIMESTAMP,
    CONSTRAINT fk_certification_history_certification FOREIGN KEY (certification_ref) REFERENCES certifications (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS exams (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_code           VARCHAR(50)    NOT NULL UNIQUE,
    exam_name           VARCHAR(255)   NOT NULL,
    certification_level VARCHAR(10)    NOT NULL,
    duration_minutes    INT            NOT NULL,
    total_marks         DECIMAL(10, 2) NOT NULL,
    passing_percentage  DECIMAL(5, 2)  NOT NULL,
    total_questions     INT            NOT NULL DEFAULT 30,
    low_severity_percentage    DECIMAL(5, 2) NOT NULL DEFAULT 20.00,
    medium_severity_percentage DECIMAL(5, 2) NOT NULL DEFAULT 40.00,
    high_severity_percentage   DECIMAL(5, 2) NOT NULL DEFAULT 40.00,
    exam_status         VARCHAR(20)    NOT NULL,
    published           BOOLEAN        NOT NULL,
    scheduled_start_time TIMESTAMP,
    scheduled_end_time   TIMESTAMP,
    created_by          VARCHAR(100)   NOT NULL,
    created_date        TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100),
    updated_date        TIMESTAMP,
    CONSTRAINT chk_exam_level            CHECK (certification_level IN ('L1', 'L2', 'L3')),
    CONSTRAINT chk_exam_status           CHECK (exam_status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'PASSED', 'FAILED', 'INVALIDATED')),
    CONSTRAINT chk_exam_duration         CHECK (duration_minutes > 0),
    CONSTRAINT chk_exam_total_marks      CHECK (total_marks >= 0),
    CONSTRAINT chk_exam_passing_percentage CHECK (passing_percentage >= 0 AND passing_percentage <= 100),
    CONSTRAINT chk_exam_total_questions   CHECK (total_questions > 0),
    CONSTRAINT chk_exam_severity_percentages CHECK (low_severity_percentage >= 0 AND low_severity_percentage <= 100
                                                AND medium_severity_percentage >= 0 AND medium_severity_percentage <= 100
                                                AND high_severity_percentage >= 0 AND high_severity_percentage <= 100),
    CONSTRAINT chk_exam_severity_mix_total CHECK (low_severity_percentage + medium_severity_percentage
                                                  + high_severity_percentage = 100)
);

CREATE TABLE IF NOT EXISTS certification_applications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_ref             BIGINT      NOT NULL,
    exam_ref             BIGINT,
    certification_level  VARCHAR(10) NOT NULL,
    application_status   VARCHAR(20) NOT NULL,
    payment_status       VARCHAR(20) NOT NULL,
    applied_on           DATE        NOT NULL,
    scheduled_exam_time  TIMESTAMP,
    remarks              VARCHAR(1000),
    created_by           VARCHAR(100) NOT NULL,
    created_date         TIMESTAMP    NOT NULL,
    updated_by           VARCHAR(100),
    updated_date         TIMESTAMP,
    CONSTRAINT fk_certification_applications_user FOREIGN KEY (user_ref) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_certification_applications_exam FOREIGN KEY (exam_ref) REFERENCES exams (id) ON DELETE SET NULL,
    CONSTRAINT chk_application_level   CHECK (certification_level IN ('L1', 'L2', 'L3')),
    CONSTRAINT chk_application_status  CHECK (application_status IN ('APPLIED', 'ELIGIBLE', 'IN_PROGRESS', 'PASSED', 'FAILED', 'TERMINATED', 'REJECTED', 'EXPIRED')),
    CONSTRAINT chk_application_payment_status CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED'))
);

CREATE TABLE IF NOT EXISTS questions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_code        VARCHAR(50)    NOT NULL UNIQUE,
    certification_level  VARCHAR(10)    NOT NULL,
    question_category    VARCHAR(20)    NOT NULL,
    question_type        VARCHAR(20)    NOT NULL,
    question_text        VARCHAR(4000)  NOT NULL,
    options_json         CLOB           NOT NULL,
    correct_options_json CLOB           NOT NULL,
    severity             VARCHAR(10)    NOT NULL,
    marks                DECIMAL(10, 2) NOT NULL,
    active               BOOLEAN        NOT NULL,
    created_by           VARCHAR(100)   NOT NULL,
    created_date         TIMESTAMP      NOT NULL,
    updated_by           VARCHAR(100),
    updated_date         TIMESTAMP,
    CONSTRAINT chk_question_level    CHECK (certification_level IN ('L1', 'L2', 'L3')),
    CONSTRAINT chk_question_category CHECK (question_category IN ('Technical', 'Functional', 'Compliance', 'General')),
    CONSTRAINT chk_question_type     CHECK (question_type IN ('Single Choice', 'Multiple Choice')),
    CONSTRAINT chk_question_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE TABLE IF NOT EXISTS payments (
    id                          BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id              VARCHAR(100)    NOT NULL UNIQUE,
    user_ref                    BIGINT          NOT NULL,
    exam_ref                    BIGINT          NOT NULL,
    certification_application_ref BIGINT,
    amount                      DECIMAL(12, 2)  NOT NULL,
    currency                    VARCHAR(10)     NOT NULL,
    provider                    VARCHAR(30)     NOT NULL,
    payment_status              VARCHAR(20)     NOT NULL,
    payment_date                TIMESTAMP,
    provider_reference          VARCHAR(100),
    provider_order_id           VARCHAR(100),
    created_by                  VARCHAR(100)    NOT NULL,
    created_date                TIMESTAMP       NOT NULL,
    updated_by                  VARCHAR(100),
    updated_date                TIMESTAMP,
    CONSTRAINT fk_payments_user        FOREIGN KEY (user_ref) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_exam        FOREIGN KEY (exam_ref) REFERENCES exams (id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_application FOREIGN KEY (certification_application_ref) REFERENCES certification_applications (id) ON DELETE SET NULL,
    CONSTRAINT chk_payments_status     CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED'))
);

CREATE TABLE IF NOT EXISTS exam_sessions (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_token            UUID         NOT NULL UNIQUE,
    user_ref                 BIGINT       NOT NULL,
    exam_ref                 BIGINT       NOT NULL,
    -- Nullable: legacy sessions may have no identifiable application. See V24.
    application_ref          BIGINT,
    session_start_time       TIMESTAMP    NOT NULL,
    session_end_time         TIMESTAMP,
    session_status           VARCHAR(20)  NOT NULL,
    violation_count          INT          NOT NULL,
    browser_fingerprint      VARCHAR(255),
    ip_address               VARCHAR(64),
    selected_question_ids_json CLOB,
    -- Autosaved draft of the attempt in flight; see V25. Read only on resume,
    -- never by scoring.
    answers_draft_json       CLOB,
    marked_for_review_json   CLOB,
    last_question_number     INT,
    progress_saved_at        TIMESTAMP,
    created_by               VARCHAR(100) NOT NULL,
    created_date             TIMESTAMP    NOT NULL,
    updated_by               VARCHAR(100),
    updated_date             TIMESTAMP,
    CONSTRAINT fk_exam_sessions_user FOREIGN KEY (user_ref) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_sessions_exam FOREIGN KEY (exam_ref) REFERENCES exams (id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_sessions_application FOREIGN KEY (application_ref) REFERENCES certification_applications (id) ON DELETE SET NULL,
    CONSTRAINT chk_exam_session_status CHECK (session_status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'PASSED', 'FAILED', 'INVALIDATED'))
);

CREATE TABLE IF NOT EXISTS exam_attempts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_session_ref    BIGINT         NOT NULL,
    total_questions     INT            NOT NULL,
    attempted_questions INT            NOT NULL,
    correct_answers     INT            NOT NULL,
    wrong_answers       INT            NOT NULL,
    obtained_marks      DECIMAL(10, 2) NOT NULL,
    percentage          DECIMAL(5, 2)  NOT NULL,
    result_status       VARCHAR(10)    NOT NULL,
    submitted_at        TIMESTAMP,
    created_by          VARCHAR(100)   NOT NULL,
    created_date        TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100),
    updated_date        TIMESTAMP,
    CONSTRAINT fk_exam_attempts_session     FOREIGN KEY (exam_session_ref) REFERENCES exam_sessions (id) ON DELETE CASCADE,
    CONSTRAINT chk_exam_attempt_result_status CHECK (result_status IN ('PASS', 'FAIL'))
);

CREATE TABLE IF NOT EXISTS certificates (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_number VARCHAR(100)  NOT NULL UNIQUE,
    certification_ref  BIGINT        NOT NULL,
    exam_attempt_ref   BIGINT        NOT NULL,
    certificate_url    VARCHAR(4000),
    qr_code_url        VARCHAR(4000),
    verification_url   VARCHAR(4000) NOT NULL,
    issue_date         DATE          NOT NULL,
    expiry_date        DATE          NOT NULL,
    created_by         VARCHAR(100)  NOT NULL,
    created_date       TIMESTAMP     NOT NULL,
    updated_by         VARCHAR(100),
    updated_date       TIMESTAMP,
    CONSTRAINT fk_certificates_certification FOREIGN KEY (certification_ref) REFERENCES certifications (id) ON DELETE CASCADE,
    CONSTRAINT fk_certificates_attempt       FOREIGN KEY (exam_attempt_ref) REFERENCES exam_attempts (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS violations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_session_ref BIGINT       NOT NULL,
    violation_type   VARCHAR(80)  NOT NULL,
    violation_level  INT          NOT NULL,
    description      VARCHAR(4000),
    detected_at      TIMESTAMP    NOT NULL,
    action_taken     VARCHAR(80),
    created_by       VARCHAR(100) NOT NULL,
    created_date     TIMESTAMP    NOT NULL,
    updated_by       VARCHAR(100),
    updated_date     TIMESTAMP,
    CONSTRAINT fk_violations_session    FOREIGN KEY (exam_session_ref) REFERENCES exam_sessions (id) ON DELETE CASCADE,
    -- 0 is legal and means "flagged for review, no strike"; see V22.
    CONSTRAINT chk_violation_level      CHECK (violation_level >= 0)
);

CREATE TABLE IF NOT EXISTS video_recordings (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_session_ref           BIGINT        NOT NULL,
    file_location              VARCHAR(4000) NOT NULL,
    recording_start_time       TIMESTAMP     NOT NULL,
    recording_end_time         TIMESTAMP,
    recording_duration_seconds BIGINT,
    created_by                 VARCHAR(100)  NOT NULL,
    created_date               TIMESTAMP     NOT NULL,
    updated_by                 VARCHAR(100),
    updated_date               TIMESTAMP,
    CONSTRAINT fk_video_recordings_session FOREIGN KEY (exam_session_ref) REFERENCES exam_sessions (id) ON DELETE CASCADE
);

-- Mirrors V21__add_ai_proctoring_evidence.sql for the H2 dev profile.
-- Large proctoring frames are isolated here so scans of `violations` stay cheap.
CREATE TABLE IF NOT EXISTS proctor_evidence_blobs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_ref      BIGINT       NOT NULL,
    exam_session_ref   BIGINT       NOT NULL,
    storage_kind       VARCHAR(20)  NOT NULL DEFAULT 'INLINE_BASE64',
    media_type         VARCHAR(60)  NOT NULL DEFAULT 'image/jpeg',
    evidence_payload   CLOB,
    object_storage_key VARCHAR(512),
    payload_bytes      BIGINT       NOT NULL DEFAULT 0,
    frame_width        INT,
    frame_height       INT,
    captured_at        TIMESTAMP    NOT NULL,
    created_by         VARCHAR(100) NOT NULL,
    created_date       TIMESTAMP    NOT NULL,
    updated_by         VARCHAR(100),
    updated_date       TIMESTAMP,
    CONSTRAINT fk_evidence_violation FOREIGN KEY (violation_ref) REFERENCES violations (id) ON DELETE CASCADE,
    CONSTRAINT fk_evidence_session   FOREIGN KEY (exam_session_ref) REFERENCES exam_sessions (id) ON DELETE CASCADE,
    CONSTRAINT chk_evidence_storage_kind CHECK (storage_kind IN ('INLINE_BASE64', 'OBJECT_STORAGE')),
    CONSTRAINT chk_evidence_payload_bytes CHECK (payload_bytes >= 0)
);

-- Columns added after the tables above were first shipped.
--
-- The CREATE TABLE statements are all IF NOT EXISTS, so a developer's existing
-- ems_h2_db file keeps whatever shape it was created with and never picks up a
-- new column from the definition alone. These re-state the additions in a form
-- that reaches an existing database, and are no-ops on a fresh one.
--
-- application_ref is the older of the two additions (V24 on Postgres). It was
-- only ever written into the CREATE TABLE above, so every H2 database created
-- before it existed is still missing the column that the session-to-application
-- lookup selects on -- which fails the dashboard outright rather than degrading.
ALTER TABLE exam_sessions ADD COLUMN IF NOT EXISTS application_ref        BIGINT;
ALTER TABLE exam_sessions ADD COLUMN IF NOT EXISTS answers_draft_json     CLOB;
ALTER TABLE exam_sessions ADD COLUMN IF NOT EXISTS marked_for_review_json CLOB;
ALTER TABLE exam_sessions ADD COLUMN IF NOT EXISTS last_question_number   INT;
ALTER TABLE exam_sessions ADD COLUMN IF NOT EXISTS progress_saved_at      TIMESTAMP;

-- The question blueprint (V26 on Postgres). Defaults reproduce the 30-question
-- 6/12/12 paper the server built before the mix was the admin's to set, so an
-- existing database's exams keep behaving as they did until someone edits them.
ALTER TABLE exams ADD COLUMN IF NOT EXISTS total_questions            INT           DEFAULT 30 NOT NULL;
ALTER TABLE exams ADD COLUMN IF NOT EXISTS low_severity_percentage    DECIMAL(5, 2) DEFAULT 20.00 NOT NULL;
ALTER TABLE exams ADD COLUMN IF NOT EXISTS medium_severity_percentage DECIMAL(5, 2) DEFAULT 40.00 NOT NULL;
ALTER TABLE exams ADD COLUMN IF NOT EXISTS high_severity_percentage   DECIMAL(5, 2) DEFAULT 40.00 NOT NULL;

-- The gateway order id (V27 on Postgres). An H2 database created before this
-- existed still has the old payments table, and CREATE TABLE IF NOT EXISTS above
-- will not add the column to it -- so initiating a Razorpay payment would fail
-- on the very insert that opens the order.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS provider_order_id VARCHAR(100);

